package Self_Learning;

public class Constructor {
    int x;

    //  Method whose name is name as that of class is called Contructor method
    //  we don't have to write return type while declaring the Constructor
    Constructor() {
        x = 20;
    }
    public static void main(String[] args) {
        Constructor c1 = new Constructor();
        System.out.println(c1.x) ;    
    }
    }

    

